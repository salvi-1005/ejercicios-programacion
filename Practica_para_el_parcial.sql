		WHERE NEW.IdLibro = ID;

		UPDATE Libro
		SET StockDisponible = StockDisponible + 1
		WHERE NEW.IdLibro = ID;
	END IF;

	IF TG_OP = 'UPDATE' AND OLD.IdLibro <> NEW.IdLibro THEN
	
	    UPDATE Libro
		SET StockPrestado = StockPrestado - 1
		WHERE OLD.IdLibro = ID;

		UPDATE Libro
		SET StockPrestado = StockPrestado + 1
		WHERE NEW.IdLibro = ID;

		UPDATE Libro
		SET StockDisponible = StockDisponible + 1
		WHERE OLD.IdLibro = ID;

		UPDATE Libro
		SET StockDisponible = StockDisponible - 1
		WHERE NEW.IdLibro = ID;
	END IF;

	RETURN NULL;

END;
$$;

