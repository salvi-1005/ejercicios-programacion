--EL SIGUIENTE CÓDIGO:
--SELECT * FROM Usuario WHERE Nombre = '"+ nombre +"';
--Es vulnerable porque la base de datos confunde los datos del usuario con instrucciones reales 
--y ejecuta comandos maliciosos

--La SQL Injection se evita mediante consultas parametrizadas, usando un marcador ?.
--Por ejemplo, si un atacante escribe (admin' OR '1'='1) sin consulta parametrizada, devuelve siempre true
--porque 1 = 1 y le da el ok al atacante para entrar sin contraseña. Sin embargo, con consulta parametrizada,
--la única manera de que el atacante pueda entrar, es que el nombre de usuario sea literalmente
--admin' OR '1'='1, lo cual es imposible.

CREATE INDEX idx_email ON Cliente(Email);

CREATE INDEX idx_apellido_nombre ON Cliente(Apellido, Nombre);

--No conviene usar índices cuando se realizan operaciones como insert, update o delete
--porque al tener que buscar en el índice tarda más tiempo en realizarlas, y cuando
--hay pocos datos, porque la base de datos tarda más tiempo en buscar dentro del índice
--que en leer toda la tabla directamente.

