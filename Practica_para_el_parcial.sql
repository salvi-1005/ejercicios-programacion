--HOSTING--

--La diferencia entre base local, base remota, hosting administrativo y hosting propio está en dónde
--se guardan los datos y quién administra los servidores.
--En la base local, los datos se almacenan en el disco duro de la computadora físic, mientras que
--en la base remota los datos se almacenan en la nube.
--En el hosting propio, el que compra o alquila un servidor se encarga de todo, mientras que
--en el hosting administrativo se alquila un servidor donde el proveedor se encarga
--del mantenimiento técnico.

--Para conectarse a una BD remota son necesarios:
--Host: Dirección IP o dominio
--Puerto: Canal específico de comunicación
--Usuario: Nombre de la cuenta
--Password: Clave de seguridad
--Database: Nombre específico de la base de datos

--DATA TYPES--
--Nombre: VARCHAR(100)
--FechaNacimiento: TIMESTAMP
--Precio: DECIMAL
--Cantidad: INT
--Email: VARCHAR(100)
--Observaciones: VARCHAR(100)

--La diferencia entre char, varchar y text está en cómo almacenan el texto en el disco y su longitud máxima
--en la computadora.
--CHAR: Longitud fija, el espacio en el disco es siempre el máximo definido, y el rendimiento es muy rápido
--VARCHAR: Longitud variable, sólo los caracteres reales ocupan más de 1 0 2 bytes
--TEXT: Longitud variable hasta 4 GB y rendimiento más lento

--La diferencia entre DATE, TIMESTAMP y TIMESTAMPTZ radica en la precisión del tiempo y en cómo manejan
--las zonas horarias.
--DATE: Almacena únicamente año, mes y día
--TIMESTAMP: Almacena fecha completa incluyendo horas, minutos y segundos
--TIMESTAMPTZ: Incluye la zona horaria además de la fecha completa.

