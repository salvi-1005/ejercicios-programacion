CREATE OR REPLACE FUNCTION precio_promedio_categoria(id_cat INT)
RETURNS DECIMAL
LANGUAGE plpgsql
AS $$
DECLARE promedio DECIMAL;
BEGIN
    SELECT COALESCE(AVG(p.Precio), 0)
	INTO promedio
	FROM Producto p RIGHT JOIN Categoria c ON c.ID = p.IdCategoria
	WHERE c.ID = id_cat;

	RETURN promedio;

END;
$$;

SELECT precio_promedio_categoria(3);

CREATE OR REPLACE FUNCTION cliente_con_mas_pedidos()
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE 
    maximo INT;
	cantidad_maxima INT;
BEGIN
    SELECT c.ID, COUNT(p.ID)
	INTO maximo, cantidad_maxima
	FROM Cliente c LEFT JOIN Pedido p ON p.IdCliente = c.ID
    GROUP BY c.ID, c.Nombre ORDER BY COUNT(p.ID) DESC LIMIT 1;

	IF cantidad_maxima = 0 THEN
        RETURN 0;
    END IF;

	RETURN maximo;

END;
$$;

SELECT cliente_con_mas_pedidos();

