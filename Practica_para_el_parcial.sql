CREATE OR REPLACE PROCEDURE mostrar_productos_categoria(id_cat INT)
LANGUAGE plpgsql
AS $$
DECLARE producto_actual RECORD;
BEGIN
    FOR producto_actual IN
	    SELECT ID, Nombre
	    FROM Producto WHERE IdCategoria = id_cat

	LOOP
	    RAISE NOTICE
		'ID: %, Nombre: %',
		producto_actual.ID,
		producto_actual.Nombre;
	END LOOP;

END;
$$;

