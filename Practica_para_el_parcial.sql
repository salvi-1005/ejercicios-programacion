CREATE OR REPLACE FUNCTION auditar_prestamo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
	    INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		(NEW.ID, 'INSERT', NEW.Inicio, NEW.Fin);
	END IF;

	IF TG_OP = 'DELETE' THEN
	    INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		(OLD.ID, 'DELETE', OLD.Inicio, OLD.Fin);
	END IF;

	IF TG_OP = 'UPDATE' THEN
	    IF OLD.ID <> NEW.ID THEN
	        INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		    (NEW.ID, 'UPDATE', OLD.Inicio, OLD.Fin);
		END IF;
		IF OLD.Inicio <> NEW.Inicio AND OLD.Fin <> NEW.Fin THEN
	        INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		    (OLD.ID, 'UPDATE', NEW.Inicio, NEW.Fin);
		END IF;
		IF OLD.Inicio <> NEW.Inicio AND OLD.Inicio = NEW.Inicio THEN
	        INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		    (OLD.ID, 'UPDATE', NEW.Inicio, OLD.Fin);
		END IF;
		IF OLD.Fin <> NEW.Fin AND OLD.Fin = NEW.Fin THEN
	        INSERT INTO Auditoria_Prestamo (IdPrestamo, Operacion, Fecha_inicio, Fecha_fin) VALUES
		    (OLD.ID, 'UPDATE', OLD.Inicio, NEW.Fin);
		END IF;
	END IF;

    RETURN NULL;
	
END;
$$;

CREATE TRIGGER trg_auditar
AFTER INSERT OR UPDATE OR DELETE
ON Prestamo
FOR EACH ROW
EXECUTE FUNCTION auditar_prestamo();

