CREATE OR REPLACE FUNCTION actualizar_pedidos()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
	    UPDATE Cliente
		SET TotalPedidos = TotalPedidos + 1
		WHERE ID = NEW.IdCliente;
	END IF;

	IF TG_OP = 'DELETE' THEN
	    UPDATE Cliente
		SET TotalPedidos = TotalPedidos - 1
		WHERE ID = OLD.IdCliente;
	END IF;

	IF TG_OP = 'UPDATE' AND OLD.IdCliente <> NEW.IdCliente THEN
	    UPDATE Cliente
		SET TotalPedidos = TotalPedidos - 1
		WHERE ID = OLD.IdCliente;

		UPDATE Cliente
		SET TotalPedidos = TotalPedidos + 1
		WHERE ID = NEW.IdCliente;
	END IF;

	RETURN NULL;

END;
$$;

