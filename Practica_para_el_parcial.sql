CREATE OR REPLACE FUNCTION cantidad_pedidos_cliente(id_cli INT)
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE Cantidad INT;
BEGIN
    SELECT COUNT(*)
	INTO Cantidad
	FROM Cliente c LEFT JOIN Pedido p ON p.IdCliente = c.ID
	WHERE c.ID = id_cli;

	RETURN Cantidad;

END;
$$;

