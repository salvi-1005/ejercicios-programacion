CREATE OR REPLACE FUNCTION impedir_eliminar_empleado_activo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE 
    FechaInicio TIMESTAMP;
	FechaFin TIMESTAMP;
BEGIN
    SELECT Inicio, Fin INTO FechaInicio, FechaFin FROM Contrato_Empleado ce
	WHERE OLD.ID = ce.IdEmpleado;

	IF NOW() BETWEEN FechaInicio AND FechaFin THEN
	    RAISE EXCEPTION 'El empleado % aún se encuentra con contrato vigente',
		OLD.ID;
	END IF;

	RETURN OLD;

END;
$$;

