CREATE OR REPLACE FUNCTION registrar_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
	    INSERT INTO Auditoria_Pedido (IdPedido, Operacion, Fecha) VALUES
		(NEW.ID, 'INSERT', NEW.Fecha);
	END IF;

	IF TG_OP = 'DELETE' THEN
	    INSERT INTO Auditoria_Pedido (IdPedido, Operacion, Fecha) VALUES
		(OLD.ID, 'DELETE', OLD.Fecha);
	END IF;

	IF TG_OP = 'UPDATE' THEN
	    IF OLD.ID <> NEW.ID THEN
	        INSERT INTO Auditoria_Pedido (IdPedido, Operacion, Fecha) VALUES
		    (NEW.ID, 'UPDATE', OLD.Fecha);
		ELSIF OLD.Fecha <> NEW.Fecha THEN
	        INSERT INTO Auditoria_Pedido (IdPedido, Operacion, Fecha) VALUES
		    (OLD.ID, 'UPDATE', NEW.Fecha);
		END IF;
	END IF;

    RETURN NULL;
	
END;
$$;

