CREATE OR REPLACE FUNCTION verificar_vigencia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE 
    FechaInicio TIMESTAMP;
	FechaFin TIMESTAMP;
BEGIN
    SELECT Inicio, Fin INTO FechaInicio, FechaFin FROM Contrato_Libro cl
	WHERE NEW.IdLibro = cl.IdLibro;

	IF (NEW.Inicio NOT BETWEEN FechaInicio AND FechaFin) OR 
	    (NEW.Fin NOT BETWEEN FechaInicio AND FechaFin) THEN
		RAISE EXCEPTION 'El libro % no está vigente en la biblioteca en esta fecha',
		    NEW.IdLibro;
	END IF;

	RETURN NEW;

END;
$$;

CREATE TRIGGER trg_verificar_si_esta_vigente
BEFORE INSERT OR UPDATE
ON Prestamo
FOR EACH ROW
EXECUTE FUNCTION verificar_vigencia();

